"""The join-order enumeration algorithms DPsize, DPsub and DPccp, which fill a plan table by dynamic programming."""

from __future__ import annotations

from typing import Iterator

from system.interfaces.cost_functions import CostFunction
from system.interfaces.query_optimization.planning import PlanEnumerator, PlanTable
from system.query_optimization.cardinality_table import CardinalityTable
from system.query_optimization.join_graph import JoinGraph
from system.query_optimization.plan_table import SizeBasedPlanTable, StandardPlanTable
from system.query_optimization.problems import Problem


class DP_Size(PlanEnumerator):
    """
    DPsize uses a size-based problem enumeration, i.e. it enumerates problems of increasing sizes. During the enumeration, it does
    not consider the actual join graph, which means that Cartesian Products, as well as disconnected join pairs will be enumerated. In other words,
    we also enumerate cross products in the algorithm (but then discard them).
    """

    def enumerate(
        self,
        join_graph: JoinGraph,
        cardinality_table: CardinalityTable,
        cost_function: CostFunction,
        print_info: bool = False,
    ) -> tuple[int, tuple | int, int]:
        """See :meth:`PlanEnumerator.enumerate`.

        With ``print_info``, prints every pair it enumerates, valid or invalid, and at the end how many of them were
        valid.
        """

        # Initialize plan table with the join graph
        # A size plan table stores entries according to their problem size, which
        # allows iterating through existing problems based on their size
        plan_table: SizeBasedPlanTable = SizeBasedPlanTable(
            join_graph, cost_function, cardinality_table
        )

        # Count number of pairs that were enumerated
        enumerated_pairs: int = 0

        # Count number of valid pairs
        valid_pairs: int = 0

        # Go through each pair generated by the enumerator below
        # It still needs to make sure that both problems are actually
        # connected and that they are disjoint.
        for s1, s2 in self.__generate_pairs_size_based(join_graph, plan_table):
            # Both s1 and s2 will already be in the plan table
            enumerated_pairs += 1

            # Check whether s1 and s2 are disjoint. Pairs which are not disjoint
            # are no valid pairs. They also need to be connected in the join graph.
            # this condition could be removed to also enumerate disconnected problems, i.e. cross products
            if not s1.intersects(s2) and join_graph.are_connected(s1, s2):
                valid_pairs += 1

                # Update the table with the newly generated pair
                plan_table.update_table(s1, s2, cardinality_table, cost_function)
                if print_info:
                    print(f"Enumerated valid pair {s1.as_set()}, {s2.as_set()}.")
            else:
                if print_info:
                    print(f"Enumerated invalid pair {s1.as_set()}, {s2.as_set()}.")

        problem_with_all_relations: Problem = Problem.get_problem_with_all_relations(
            len(join_graph)
        )

        if print_info:
            print(
                f"{enumerated_pairs} pairs were enumerated, out of which {valid_pairs} were valid!"
            )

        return (
            plan_table.get_costs_for_problem(problem_with_all_relations),
            plan_table.get_plan_for_problem(problem_with_all_relations),
            enumerated_pairs,
        )

    def __generate_pairs_size_based(
        self, join_graph: JoinGraph, plan_table: SizeBasedPlanTable
    ) -> Iterator[tuple[Problem, Problem]]:
        """
        Enumerate through the search space by utilizing the size of problems.
        :param join_graph: The join graph.
        :param plan_table: The underlying plan table.
        """
        num_nodes: int = len(join_graph.adjacency_matrix)
        # Enumerate all possible problem sizes starting from 2
        for main_size in range(2, num_nodes + 1):
            # Enumerate the sizes of s1 only up to main_size // 2 (inclusive)
            # to avoid duplicate work: larger sizes of s1 would only swap s1 and s2.
            for s1_size in range(1, (main_size // 2) + 1):
                s2_size: int = main_size - s1_size

                # If both sizes are equal, you need to evaluate symmetric pairs only once
                if s1_size == s2_size:
                    # Enumerate all problems of size s1_size
                    for i, s1 in enumerate(plan_table.entries_with_size(s1_size)):
                        # Evaluated entries can be addressed by an index
                        # Enumerate all problems of size s2_size, and start with index i + 1
                        # to avoid having to re-enumerate symmetric pairs
                        for s2 in plan_table.entries_with_size(s2_size, i + 1):
                            # New pair was generated
                            yield s1, s2
                else:
                    # Enumerate all problems of size s1_size
                    for s1 in plan_table.entries_with_size(s1_size):
                        # Enumerate all problems of size s2_size
                        for s2 in plan_table.entries_with_size(s2_size):
                            # New pair was generated
                            yield s1, s2


class DP_Sub(PlanEnumerator):
    """
    DPsub generates all possible pairs for each connected problem. It still generates Cartesian Products, that need to be filtered out.
    """

    def enumerate(
        self,
        join_graph: JoinGraph,
        cardinality_table: CardinalityTable,
        cost_function: CostFunction,
        print_info: bool = False,
    ) -> tuple[int, tuple | int, int]:
        """See :meth:`PlanEnumerator.enumerate`.

        With ``print_info``, prints every pair it enumerates, valid or invalid, and at the end how many of them were
        valid.
        """
        # Initialize plan table with the join graph
        plan_table: PlanTable = StandardPlanTable(
            join_graph, cost_function, cardinality_table
        )

        # Count number of pairs that were enumerated
        enumerated_pairs: int = 0
        # Count number of valid pairs
        valid_pairs: int = 0

        # Go through each generated pair and make sure that both problems s1 and s2
        # are connected
        for s1, s2 in self.__generate_pairs_sub_based(join_graph):
            enumerated_pairs += 1
            # s1 | s2 is guaranteed to be connected and disjoint as this point
            # We still need to check whether s1 and s2 themselves are connected
            # s1 and s2 are connected if they are contained in the plan table
            # meaning they were enumerated as a valid problem at an earlier point
            if s1 in plan_table and s2 in plan_table:
                valid_pairs += 1
                # Update the table with the newly generated pair
                plan_table.update_table(s1, s2, cardinality_table, cost_function)
                if print_info:
                    print(f"Enumerated valid pair {s1.as_set()}, {s2.as_set()}")
            else:
                if print_info:
                    print(f"Enumerated invalid pair {s1.as_set()}, {s2.as_set()}")

        problem_with_all_relations: Problem = Problem.get_problem_with_all_relations(
            len(join_graph)
        )

        if print_info:
            print(
                f"{enumerated_pairs} pairs were enumerated, out of which {valid_pairs} were valid"
            )

        return (
            plan_table.get_costs_for_problem(problem_with_all_relations),
            plan_table.get_plan_for_problem(problem_with_all_relations),
            enumerated_pairs,
        )

    def __generate_pairs_sub_based(
        self, join_graph: JoinGraph
    ) -> Iterator[tuple[Problem, Problem]]:
        """
        Generate the required pairs by enumerating all possible problems.
        :param join_graph: The join graph.
        """
        num_nodes: int = len(join_graph.adjacency_matrix)
        # Enumerate all problems by increasing the underlying problem number
        for i in range(1, 1 << num_nodes):
            # Find the best plan for this problem
            main_problem: Problem = Problem(i)

            # Singletons do not have to be considered
            if len(main_problem) == 1:
                continue

            # The problem also needs to be connected, otherwise
            # it would not be a valid problem
            if not join_graph.is_connected(main_problem):
                continue

            # Again, there is no need to enumerate symmetric pair twice, which can be achieved
            # by stopping the enumeration after the first half is done.
            # Setting the stop problem exactly to the singleton pointing to the
            # position of the MSB stops the enumeration exactly at this point
            stop_problem: Problem = main_problem.get_most_significant_bit()
            # Start the enumeration with the smallest singleton of the main problem, stop when the stop problem has been reached
            for s1 in Problem.enumerate_all_problems(
                main_problem, stop_problem=stop_problem
            ):
                # Generate the corresponding partner subset
                # Given that s1 | s2 == main_problem, we know s1 and s2 are connected via at least one join edge
                s2: Problem = main_problem - s1
                # New pair was generated
                yield s1, s2


def generate_connected_problems(join_graph: JoinGraph) -> Iterator[Problem]:
    """
    Generate all connected problems of the join graph, each exactly once. Starting from each singleton, from the
    highest relation down, a problem is recursively extended with its neighbors, skipping the neighbors in an exclude
    set. The exclude set holds every relation whose id is smaller than or equal to that of the starting singleton, plus
    all neighbors of the problems the current problem was grown from. The notebook PlanEnumeration.ipynb explains this
    in its section "Using the join graph for the enumeration".
    :param join_graph: The join graph.
    """
    problem_with_all_relations: Problem = Problem.get_problem_with_all_relations(
        len(join_graph)
    )

    # Top-level exclude set, always ignore neighbors whose order is <= than the current singleton. See the docstring for more details.
    exclude: Problem = problem_with_all_relations

    # Traverse all singleton sets (sets containing only one relation) as starting point. Go from the highest bit to the lowest bit.
    for singleton in reversed(problem_with_all_relations):
        yield singleton

        # Recursively extend the singleton with all its neighbors, as long as the order of the neighbor is not lower/equal than the singleton
        yield from generate_recursively(join_graph, singleton, exclude)

        # Current problem can now be considered
        exclude -= singleton


def generate_recursively(
    join_graph: JoinGraph,
    start: Problem,
    exclude: Problem,
) -> Iterator[Problem]:
    """
    Recursively extends the given start problem with its neighbors. Ignores relations contained in the exclude problem.
    :param join_graph: The join graph.
    :param start: The start problem.
    :param exclude: The exclude problem.
    """
    # Get direct neighbors of the problem, ignore those from the exclude set
    neighbors: Problem = join_graph.get_neighbors(start) - exclude

    # Get all problems contained in the neighbor set
    neighbor_problems: list[Problem] = Problem.get_all_problems(neighbors)

    # Combine all neighbor problems with the start problem
    for neighbor_problem in neighbor_problems:
        yield start | neighbor_problem

    for neighbor_problem in neighbor_problems:
        # Proceed recursively, extend the exclude set with the current neighbors
        yield from generate_recursively(
            join_graph,
            start | neighbor_problem,
            exclude | neighbors,
        )


def generate_ccp_pairs(join_graph: JoinGraph) -> Iterator[tuple[Problem, Problem]]:
    """
    Enumerate all ccp pairs of the given join graph.
    :param join_graph: The join graph.
    """
    for csg in generate_connected_problems(join_graph):
        # No cmp problem may overlap the csg, so the csg itself is always excluded
        # We also always want to ignore cmp problems that contain relations whose number is smaller than the smallest in the csg
        always_exclude_set: Problem = csg | csg.get_smaller_or_equal_relations()

        # Start the enumeration of the cmp problems with the direct neighbors of the csg problem
        csg_neighbors: Problem = join_graph.get_neighbors(csg) - always_exclude_set

        # Define an additional top-level ignore set, we still want to ignore all problems with smaller/equal numbers than the current problem
        # This time, however, we only enumerate the direct neighbors of the csg, thus we need to gradually reduce the neighbor set, instead of the whole problem.
        exclude_set: Problem = csg_neighbors

        # Again traverse all singleton problems in reversed order
        for singleton in reversed(csg_neighbors):
            yield csg, singleton

            # The exclude_set is gradually reduced, we still need to make sure that we never include a relation from the always_exclude_set
            # Make use of the already defined recursive function, as the required behavior here is exactly the same.
            for cmp_problem in generate_recursively(
                join_graph,
                singleton,
                exclude_set | always_exclude_set,
            ):
                yield csg, cmp_problem

            # Current problem can now be considered
            exclude_set -= singleton


class DP_CCP(PlanEnumerator):
    """
    Uses the join graph to enumerate all ccp pairs, without enumerating any invalid pair.
    """

    def enumerate(
        self,
        join_graph: JoinGraph,
        cardinality_table: CardinalityTable,
        cost_function: CostFunction,
        print_info: bool = False,
    ) -> tuple[int, tuple | int, int]:
        """See :meth:`PlanEnumerator.enumerate`.

        With ``print_info``, prints every pair it enumerates (all of them are valid) and at the end their number.
        """
        # Initialize plan table with the join graph
        plan_table: PlanTable = StandardPlanTable(
            join_graph, cost_function, cardinality_table
        )

        # Count number of pairs that were enumerated
        enumerated_pairs: int = 0

        # Use previously defined generator to iterator through each ccp
        # Note that no checks are required here anymore, as the ccp is guaranteed to be valid
        for s1, s2 in generate_ccp_pairs(join_graph):
            enumerated_pairs += 1

            if print_info:
                print(f"Enumerated valid pair {s1.as_set()}, {s2.as_set()}")

            # Update the table with the newly generated pair
            plan_table.update_table(s1, s2, cardinality_table, cost_function)

        problem_with_all_relations: Problem = Problem.get_problem_with_all_relations(
            len(join_graph)
        )

        if print_info:
            print(f"Enumerated {enumerated_pairs} valid pairs")

        return (
            plan_table.get_costs_for_problem(problem_with_all_relations),
            plan_table.get_plan_for_problem(problem_with_all_relations),
            enumerated_pairs,
        )
